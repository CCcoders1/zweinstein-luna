#!/usr/bin/env bash
# Bouwt bundel.js en bundel.css uit de bronbestanden. Niet met de hand bewerken.
set -euo pipefail
cd "$(dirname "$0")/.."

JS=(
  wachtrij.js fx.js reserve.js app.js economie.js lessen.js extra.js kaarten.js
  polish.js buit.js match3.js m3kunst.js kern.js kweek.js kas2.js elfjes.js
  laadscherm.js flits.js smekkies.js ui.js vakken.js doelen.js balans-data.js
  balans.js backup.js powerups.js kasplus.js personages.js spelbg.js plaag.js
  schooldagen.js fopshop.js pompoen.js kruidwinkel.js geluid.js spreuk.js
  ketel.js huispunten.js bonuskamer.js flesjes.js verloop.js minigames.js
  mijlpaal.js config-online.js vrienden.js speellog.js halloween.js versie.js
  feest.js kastaken.js kweekvolg.js samenhang.js sfeer.js verhaaljaar.js
  kringloop.js winter.js strak.js huiskamer.js huisdoel.js laatspel.js m3ronde.js menu192.js kleur194.js kleur195.js valfix.js bord209.js pad210.js meer211.js spel197.js spel198.js eind214.js pittig219.js eind221.js combo222.js hint223.js bijna224.js start225.js bord226.js pad227.js
)
CSS=(
  style.css extra.css polish.css donker.css kern.css licht.css
  halloween.css sfeer.css kringloop.css winter.css thema.css strak.css huisdoel.css laatspel.css m3ronde.css menu192.css kleur194.css kleur195.css bord196.css bord197.css bord198.css bord199.css stijl199.css intro200.css hal201.css ook202.css meer203.css kaart204.css lev205.css groet206.css stap207.css intro208.css bord209.css pad210.css meer211.css boek212.css kas213.css eind214.css popup215.css hud216.css goud217.css kaart218.css pittig219.css gevoel220.css eind221.css combo222.css hint223.css bijna224.css start225.css bord226.css pad227.css
)

python3 - "$PWD" << 'PY'
import sys, re, pathlib
root = pathlib.Path(sys.argv[1])
js = '''
  wachtrij.js fx.js reserve.js app.js economie.js lessen.js extra.js kaarten.js
  polish.js buit.js match3.js m3kunst.js kern.js kweek.js kas2.js elfjes.js
  laadscherm.js flits.js smekkies.js ui.js vakken.js doelen.js balans-data.js
  balans.js backup.js powerups.js kasplus.js personages.js spelbg.js plaag.js
  schooldagen.js fopshop.js pompoen.js kruidwinkel.js geluid.js spreuk.js
  ketel.js huispunten.js bonuskamer.js flesjes.js verloop.js minigames.js
  mijlpaal.js config-online.js vrienden.js speellog.js halloween.js versie.js
  feest.js kastaken.js kweekvolg.js samenhang.js sfeer.js verhaaljaar.js
  kringloop.js winter.js strak.js huiskamer.js huisdoel.js laatspel.js m3ronde.js menu192.js kleur194.js kleur195.js valfix.js bord209.js pad210.js meer211.js spel197.js spel198.js eind214.js pittig219.js eind221.js combo222.js hint223.js bijna224.js start225.js bord226.js pad227.js
'''.split()
css = '''
  style.css extra.css polish.css donker.css kern.css licht.css
  halloween.css sfeer.css kringloop.css winter.css thema.css strak.css huisdoel.css laatspel.css m3ronde.css menu192.css kleur194.css kleur195.css bord196.css bord197.css bord198.css bord199.css stijl199.css intro200.css hal201.css ook202.css meer203.css kaart204.css lev205.css groet206.css stap207.css intro208.css bord209.css pad210.css meer211.css boek212.css kas213.css eind214.css popup215.css hud216.css goud217.css kaart218.css pittig219.css gevoel220.css eind221.css combo222.css hint223.css bijna224.css start225.css bord226.css pad227.css
'''.split()

out_js = ["/* auto-generated by tests/bundel.sh — niet met de hand bewerken */\n"]
for name in js:
    text = (root / name).read_text(encoding='utf-8')
    # Voorkom dat een bestand-niveau 'use strict' de hele bundel strikt maakt.
    text = re.sub(r"^\s*'use strict'\s*;\s*", "", text, count=1)
    text = re.sub(r'^\s*"use strict"\s*;\s*', "", text, count=1)
    out_js.append(f"\n;/* === {name} === */\n")
    out_js.append(text)
    if not text.endswith('\n'):
        out_js.append('\n')
(root / 'bundel.js').write_text(''.join(out_js), encoding='utf-8')

out_css = ["/* auto-generated by tests/bundel.sh — niet met de hand bewerken */\n"]
for name in css:
    text = (root / name).read_text(encoding='utf-8')
    out_css.append(f"\n/* === {name} === */\n")
    out_css.append(text)
    if not text.endswith('\n'):
        out_css.append('\n')
(root / 'bundel.css').write_text(''.join(out_css), encoding='utf-8')
print(f"bundel.js {sum(1 for _ in out_js)} delen, {(root/'bundel.js').stat().st_size} bytes")
print(f"bundel.css {(root/'bundel.css').stat().st_size} bytes")
PY
node --check bundel.js
# Minify: kleinere eerste lading, bronbestanden blijven leesbaar.
if command -v npx >/dev/null 2>&1; then
  npx --yes esbuild bundel.js --minify --legal-comments=none --outfile=bundel.js.tmp
  npx --yes esbuild bundel.css --minify --legal-comments=none --outfile=bundel.css.tmp
  mv bundel.js.tmp bundel.js
  mv bundel.css.tmp bundel.css
  node --check bundel.js
  echo "bundel minified $(wc -c < bundel.js) js, $(wc -c < bundel.css) css"
fi
echo "bundel ok"
